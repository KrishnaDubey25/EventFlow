must(venue.includes('<OrganizerLayout') && venue.includes('<OperatorLayout') && venue.includes('<AppLayout'),'Indoor map keeps correct role sidebar/layout');
must(floor.includes('Request help') && floor.includes('operators nearby'),'Attendee sees nearby operators and help action');
must(collab.includes('HelpRequest') && collab.includes('createHelpRequest') && collab.includes('updateHelpRequest'),'Help request lifecycle persisted');
